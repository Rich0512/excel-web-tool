// 貼上名單的社團名稱與星期推測規則（guessClubAndDay）：
// 哪些標題寫法要推得出來、標題列與資料列不可當成社團、星期與上課時間的寫法。
// 姓名不可被推成社團名稱的案例在 paste-guess-names.test.mjs。
// 測試資料的姓名全部是虛構的（測試生301_05、測試甲…）。
import { loadSite, makeReporter, guessChecker } from './harness.mjs';
const R = makeReporter('貼上名單：社團名稱與星期的推測規則');
const expect = guessChecker(R, loadSite());

const DATA = '301\t05\t測試生301_05\n302\t11\t測試生302_11';
const HEADER = '班級\t座號\t姓名\n' + DATA;            // Tab 分隔的標題列
const H = '班級 座號 姓名\n301 05 測試生301_05';       // 空白分隔的標題列
const H1 = '\n班級\t座號\t姓名\n301\t05\t測試生301_05'; // 接在標題之後的一筆資料
const R1 = '\n301\t05\t測試生301_05\n302\t11\t測試生302_11'; // 接在標題之後、沒有標題列的資料

// ---- 沒有標題列：社團與星期寫在同一行
expect('沒有標題列「桌遊社 週三」', '桌遊社 週三\n' + DATA, '桌遊社', '週三');
expect('沒有標題列「週三 桌遊社」', '週三 桌遊社\n' + DATA, '桌遊社', '週三');
expect('沒有標題列「桌遊社 星期三」', '桌遊社 星期三\n' + DATA, '桌遊社', '週三');
expect('沒有標題列「桌遊社，週三」（逗號不當成欄位分隔）', '桌遊社，週三\n' + DATA, '桌遊社', '週三');
expect('沒有標題列「桌遊社  週三」（兩個空白）', '桌遊社  週三\n' + DATA, '桌遊社', '週三');
expect('沒有標題列「桌遊社週三」（連寫星期）', '桌遊社週三\n' + DATA, '桌遊社', '週三');
expect('只有 1 行「桌遊社 週三」', '桌遊社 週三', '桌遊社', '週三');
expect('沒有標題列「延平國小 舞蹈社 錄取名單」', '延平國小 舞蹈社 錄取名單\n' + DATA, '舞蹈社', null);
expect('沒有標題列「115學年度第二學期 週三 直笛社 錄取名單」', '115學年度第二學期 週三 直笛社 錄取名單\n' + DATA, '直笛社', '週三');
expect('沒有標題列「直笛社團錄取名單」', '直笛社團錄取名單\n' + DATA, '直笛社', null);
expect('沒有標題列、4 字以上以「隊」結尾「樂樂棒球隊」', '樂樂棒球隊\n' + DATA, '樂樂棒球隊', null);
expect('沒有標題列、4 字以上以「社」結尾「兒童繪畫社」', '兒童繪畫社\n' + DATA, '兒童繪畫社', null);
expect('沒有標題列、4 字以上以「課」結尾「書法研習課 週三」', '書法研習課 週三\n' + DATA, '書法研習課', '週三');
expect('沒有標題列「Scratch程式社 週三」（英文字母＋社團）', 'Scratch程式社 週三\n' + DATA, 'Scratch程式社', '週三');
expect('沒有標題列「LEGO 社 錄取名單」', 'LEGO 社 錄取名單\n' + DATA, 'LEGO社', null);
expect('不可見字元夾在社團標題裡仍推得出', `桌遊社${String.fromCharCode(0x200f)} 週三\n` + DATA, '桌遊社', '週三');

// ---- 沒有標題列時，和姓名分不出來的短名稱不推測（寧可漏推，不能把姓名填進社團名稱）
expect('沒有標題列、單獨一行「圍棋」不推測', '圍棋\n' + DATA, null, null);
expect('沒有標題列、單獨一行「魔術」不推測', '魔術\n' + DATA, null, null);
expect('沒有標題列「圍棋 週三」不推測（圍棋像姓名）', '圍棋 週三\n' + DATA, null, null);
expect('沒有標題列、3 字且沒有星期與標題字詞「足球隊」不推測', '足球隊\n' + DATA, null, null);
expect('沒有標題列、3 字且沒有星期與標題字詞「桌遊社」不推測', '桌遊社\n' + DATA, null, null);
expect('沒有標題列「每週三 陶藝課」只推星期（3 字以下只接受「社」結尾）', '每週三 陶藝課\n' + DATA, null, '週三');

// ---- 標題列之前的行
expect('標題列之前「圍棋」', '圍棋\n' + HEADER, '圍棋', null);
expect('空白標題列之前「圍棋」', '圍棋\n' + H, '圍棋', null);
expect('標題列之前「桌遊社週三」', '桌遊社週三\n' + HEADER, '桌遊社', '週三');
expect('標題列之前「桌遊社(週三)」', '桌遊社(週三)\n' + HEADER, '桌遊社', '週三');
expect('標題列之前「桌遊社 週三」', '桌遊社 週三\n' + H, '桌遊社', '週三');
expect('標題列之前「每週一次的桌遊社」：「週一」不算星期', '每週一次的桌遊社\n' + HEADER, '每週一次的桌遊社', null);
expect('社團名稱含「名」：「名偵探社」', '名偵探社\n' + HEADER, '名偵探社', null);
expect('社團名稱含「座」：「星座研究社」', '星座研究社\n' + HEADER, '星座研究社', null);
expect('「週二烏克麗麗A班」去掉星期與 A班', '週二烏克麗麗A班\n' + HEADER, '烏克麗麗', '週二');
expect('標題列之前「周一兒童繪畫社 (一 10,11)」去掉上課時間括號', '周一兒童繪畫社 (一 10,11)\n' + HEADER, '兒童繪畫社', '週一');
expect('空白標題列之前「周一兒童繪畫社 (一 10,11)」', '周一兒童繪畫社 (一 10,11)\n' + H, '兒童繪畫社', '週一');
expect('標題列之前「直笛社團錄取名單」', '直笛社團錄取名單\n' + HEADER, '直笛社', null);
expect('標題列之前「115學年度 舞蹈社 錄取名單」（數字在標題字詞裡）', '115學年度 舞蹈社 錄取名單\n' + H, '舞蹈社', null);
expect('標題列之前「Scratch 程式社」', 'Scratch 程式社\n' + H, 'Scratch程式社', null);
expect('標題列之前「每週三 陶藝課」推得出社團與星期', '每週三 陶藝課\n' + H, '陶藝課', '週三');

// ---- 標題列、資料列本身不推測
expect('從標題列開始貼', HEADER, null, null);
expect('從空白分隔的標題列開始貼', '班級 座號 姓名\n301 05 測試甲', null, null);
expect('只有「姓名」一欄的標題', '姓名\n測試甲\n測試乙', null, null);
expect('標題列前一行是欄位說明「座號 姓名」', '座號 姓名\n' + DATA, null, null);
expect('Tab 分隔的資料列不推測', DATA, null, null);
expect('空白分隔的資料列不推測', '301 05 測試甲\n302 11 測試乙', null, null);
expect('逗號分隔的資料列不推測', '301,05,測試甲\n302,11,測試乙', null, null);

// ---- 星期與上課時間的寫法
expect('「每週三 圍棋社」的星期是週三', '每週三 圍棋社' + H1, undefined, '週三');
expect('「圍棋社 每週一次」的「週一次」不算星期', '圍棋社 每週一次' + H1, undefined, null);
expect('「圍棋社 兩週一次 週四」的星期是週四', '圍棋社 兩週一次 週四' + H1, undefined, '週四');
expect('標題列之前含時間「圍棋社 週三 15:30」', '圍棋社 週三 15:30' + H1, '圍棋社', '週三');
expect('標題列之前含時段「圍棋社 週三 15:30-17:00」', '圍棋社 週三 15:30-17:00' + H1, '圍棋社', '週三');
expect('沒有標題列含時間「圍棋社 週三 15:30」', '圍棋社 週三 15:30' + R1, '圍棋社', '週三');
expect('標題列之前全形數字星期「桌遊社 週３」', '桌遊社 週３' + H1, '桌遊社', '週三');
expect('沒有標題列全形數字星期「桌遊社 週３」', '桌遊社 週３' + R1, '桌遊社', '週三');
R.done();
